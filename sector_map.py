def get_sector(symbol: str) -> str:
    """銘柄コードからセクターを返す。未分類は 'その他'。"""
    code = symbol.replace(".T", "").strip()
    for sector, codes in SECTOR_SYMBOLS.items():
        if code in codes:
            return sector
    return "その他"


def count_by_sector(symbols_in_position: list[str]) -> dict[str, int]:
    """現在保有中の銘柄コードリストを受け、セクター別保有数を返す。"""
    counts = {}
    for s in symbols_in_position:
        sec = get_sector(s)
        counts[sec] = counts.get(sec, 0) + 1
    return counts


def can_add_sector(symbol: str, current_positions: list[str],
                   max_per_sector: int = 1) -> bool:
    """この銘柄を追加してもセクター上限を超えないか判定。"""
    sec = get_sector(symbol)
    if sec == "その他":
        return True   # 分類不明はカウント外
    counts = count_by_sector(current_positions)
    return counts.get(sec, 0) < max_per_sector


