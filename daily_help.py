r"""daily_help.py - `.\daily -h` / `.\dailyfast -h` のヘルプ本文。

なぜ .bat に直接書かないか
--------------------------
cmd.exe は .bat を OEM コードページ(日本語Windowsは932)で読む。CP932 の2バイト目には
0x7C(|) や 0x26(&) を持つ文字があり、cmd がそれを演算子と解釈して行を分割し、断片を
コマンドとして実行しようとする(CLAUDE.md 18.10.1: 実際に ldt.bat が壊れた)。
そのため .bat 側は ASCII のみに保ち、日本語の本文は Python から出す。

出力先のコンソールは CP932 のことが多いので、絵文字など CP932 に無い文字は使わない。
念のため stdout は errors="replace" にして、落ちないようにしてある。
"""
from __future__ import annotations

import sys

try:                       # CP932 に無い文字が混じっても落とさない
    sys.stdout.reconfigure(errors="replace")
except Exception:
    pass

_COMMON = r"""
================================================================
 共通の注意
================================================================
 * .\daily / 発注 / .\watch は **必ず1つずつ** 実行すること。
   kabu の有効トークンは1つしかないので、同時に走らせると 401 の
   取り合いになる (CLAUDE.md 18.4)。

 * 実行タイミング: 朝 8:45 まで。9:00 の寄りまでに発注リストが要る。

 * その取引日の初回はBTキャッシュを作り直すので遅い。2回目以降は速い。

 * 出力: signals_holdout_all_both_<日付>.html
   既定タブは lss (ロング銘柄ショート)。

================================================================
 関連コマンド
================================================================
 .\daily         朝の発注リスト (フル)              8:45まで
 .\dailyfast     同じ発注リスト (軽量・H タブ付き)  8:45まで
 .\watch         日中の監視・自動決済               寄り〜15:30
 .\fills         その日の実約定・実損益             15:30以降
 .\tenkan        転換の記録 (発注には使わない)       .\fills の後
 .\delay         損切り遅延を1日ぶん検証            .\fills の後

 H(指値売り)の実発注:
   python lss_budget_cap.py --entry-mode limit --limit-ticks -5 ^
          --budget-multiple 1.0 --execute --prod
   ※ --budget-multiple 1.0 は必須。指値は寄りで一斉に約定するので
      over-subscribe (出しすぎて後から取消) が効かない。
"""

_DAILY = r"""
================================================================
 .\daily - 朝の発注リスト (フル版)
================================================================
 ロング / ショート / lss の3方向レポートを作り、最後に発注サーバを
 起動する (レポート上の「発注に切替」「監視に切替」ボタン用)。

 使い方:
   .\daily                     そのまま実行
   .\daily <オプション>        オプションは run_signals_holdout_all.py に素通し

----------------------------------------------------------------
 速くしたいとき (効果の大きい順)
----------------------------------------------------------------
 .\daily --no-long --no-short --no-symbol-detail --price-ranges 6000
     lss だけ・1ペイン・銘柄別タブ無し = 最速。発注リストは変わらない。

 .\daily --no-symbol-detail
     銘柄別の損益タブを落とす。このタブは **シグナル銘柄1つにつき損益
     ビルドを丸ごと1回やり直す** (混んだ日は69回)。実行時間もメモリも
     ここが最大の支配要因。迷ったらまずこれを落とす。

 .\daily --symbol-detail-limit 20
     タブは残して BT上位20銘柄だけにする (中間の選択肢)。

 .\daily --no-long --no-short
     ロング/ショートのペインを落とす。発注するのは lss タブ。

 .\daily --price-ranges 6000
     価格帯ペインを 1,000-6,000 の1つだけにする (既定は 6000 と無制限の2つ)。

 .\daily --days 365
     損益タブの表示窓 (既定180日)。長くすると t 検定の月数が増える。

 .\daily --no-serve
     レポートだけ作って発注サーバを起動しない。

----------------------------------------------------------------
 このバッチが固定している設定 (実機の正)
----------------------------------------------------------------
 LSS_STOP_DELAY_BARS=1   損切り遅延1本。watch.bat と揃えてある。
                         ずらすとレポートとライブが食い違う (18.9 の鉄則)。
 LSS_BT_TAB_MIN=30       BT下限30 = 候補プールの床 = 実質フィルタ無し。
                         BTに識別力が無いため (18.12 / 18.24)。
 LSS_H_LIMIT_TICKS=-5    H の指値位置。前日終値-5ティック。
 LSS_ASOF_BT=1           過去の取引を **当時の** BT で採点する。
                         切ると93.7%の取引が今日のBTで採点され先読みになる (18.11)。
 LSS_TRADES_CSV=lss_trades.csv
                         決済済みトレードを全部書き出す。.\fills の突合に使う。

 実行前に重い研究フラグ (LSS_CLOSESTOP_RESWEEP 等) を毎回クリアする。
 付けっぱなしだと毎回数百秒の終値損切り比較が走ってしまうため。

 ★ 素の python run_signals_holdout_all.py で叩かないこと。
   上の env は .bat が渡している。素で叩くと as-of BT が切れて先読みになる (18.10.1)。

----------------------------------------------------------------
 H タブについて
----------------------------------------------------------------
 .\daily では H タブは **出しません** (lss パスを2周するので約2倍遅く、
 8:45 の発注リストを遅らせないため)。H タブが要るときは .\dailyfast。
"""

_FAST = r"""
================================================================
 .\dailyfast - 朝の発注リスト (軽量版・H タブ付き)
================================================================
 銘柄選定・BTランキング・発注リストは .\daily とまったく同じ。
 発注判断に効かない重いタブだけを落としてある。

 使い方:
   .\dailyfast                 そのまま実行
   .\dailyfast --days 365      損益タブの窓を365日に
   .\dailyfast --no-serve      発注サーバを起動しない

----------------------------------------------------------------
 落としているもの (どれも発注銘柄を変えない)
----------------------------------------------------------------
 --no-symbol-detail    銘柄別の損益タブ。シグナル1銘柄につき損益ビルドを
                       丸ごと1回やり直すので、実行時間の最大要因。
 --no-long --no-short  ロング/ショートのペイン。発注するのは lss タブ。
 --price-ranges 6000   価格帯ペインを1つに。
 --no-tenkan           転換タブ。18.26b で「記録専用・発注ルールには
                       組み込まない」と決着済み。5分足から数百件を再計算する。
 --no-market           相場環境/トレンド期間/エントリー分析タブ。日経を取りに行き
                       20万字以上のHTMLを出すが、lss/H の発注判断には効かない。

----------------------------------------------------------------
 追加しているもの
----------------------------------------------------------------
 --h-tab   「H 指値ショート」方向タブを追加する (.\daily には無い)。
           シグナル・銘柄・決済は lss タブと同一で、違うのは注文の出し方だけ。
             現行: 前日終値-1ティックに **逆指値** (下がってきたら約定)
             H   : 前日終値-5ティックに **指値**   (上がってきたら/寄りが上なら約定)
           このタブの発注ボタンは本当に **指値売り** を送る。
           コスト: lss パスを2周するので約2倍遅い。

 検証ブロック (H タブの隣、lss タブの損益レポート内「H 前日終値の指値」明細タブ):
   * H の設定比較   指値位置 x 寄指か x 損切り遅延(delay 0/1/2/3)
   * 現行 / E / H の比較
   * 発注順の比較   ランダム12シードのノイズ帯つき
   * 選定からの経過月数
   すべて **同じ1回の実行** から作る。設定ごとにレポートを回して比べては
   いけない (18.24: 実行が変わると比較相手の現行まで動く)。

----------------------------------------------------------------
 このバッチが固定している設定
----------------------------------------------------------------
 daily.bat と同じ (LSS_STOP_DELAY_BARS=1 / LSS_BT_TAB_MIN=30 /
 LSS_H_LIMIT_TICKS=-5 / LSS_ASOF_BT=1 / LSS_TRADES_CSV)。

 サイジングは **全銘柄100株固定**。ATR均等は試して戻した (2026-08-11)。
 +747 -> +775 円/件 (+3.7%) はノイズ帯の内側で、前半2位/後半2位 =
 どちらの期間でも100株固定に負けていたため。戻すなら .bat の
 LSS_SIZE_MODE / LSS_SIZE_TARGET のコメントを外す。

----------------------------------------------------------------
 フル版が要るとき
----------------------------------------------------------------
 .\daily                          全部入り
 .\daily --symbol-detail-limit 20 中間 (銘柄別タブをBT上位20だけ残す)
"""


def main() -> int:
    which = (sys.argv[1] if len(sys.argv) > 1 else "daily").strip().lower()
    print(_FAST if which.startswith("fast") else _DAILY)
    print(_COMMON)
    print("  詳しいオプション一覧 (素の argparse):")
    print("    python run_signals_holdout_all.py --help")
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
